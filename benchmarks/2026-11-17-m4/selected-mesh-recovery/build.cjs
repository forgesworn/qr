const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict')
if(process.argv.length!==5)throw Error('Usage: node build.cjs ROOT SOURCE NEW_BUILD')
const [root,source,out]=process.argv.slice(2).map(p=>path.resolve(p)),ts=require(path.join(root,'node_modules/typescript'))
const sha=x=>crypto.createHash('sha256').update(x).digest('hex')
const instrument=JSON.parse(fs.readFileSync(source+'/identity.json'))
assert.equal(instrument.revision,'0fdcd6262f0cd5ddcd7ec6bfba5d131df01c9a37')
assert.equal(instrument.instrumentSha256,sha(fs.readFileSync(path.join(__dirname,'instrument.py'))))
assert.equal(sha(fs.readFileSync(source+'/package.json')),instrument.packageJsonSha256)
assert.equal(JSON.parse(fs.readFileSync(source+'/package.json')).type,'module')
const names=fs.readdirSync(source).filter(n=>n.endsWith('.ts')).sort()
assert.deepEqual(names,Object.keys(instrument.copiedFiles).sort())
for(const name of names)assert.equal(sha(fs.readFileSync(source+'/'+name)),instrument.copiedFiles[name])
const host={getCurrentDirectory:()=>root,getCanonicalFileName:x=>x,getNewLine:()=> '\n'}
const check=(items,label)=>{if(items.length){process.stderr.write(ts.formatDiagnosticsWithColorAndContext(items,host));throw Error(label)}}
const config=ts.readConfigFile(root+'/tsconfig.json',ts.sys.readFile);check(config.error?[config.error]:[],'Read config')
const parsed=ts.parseJsonConfigFileContent(config.config,ts.sys,root);check(parsed.errors,'Parse config')
const options={...parsed.options,rootDir:source,outDir:out+'/public',noEmit:true},roots=names.map(n=>source+'/'+n)
check(ts.getPreEmitDiagnostics(ts.createProgram(roots,options)),'Copied observer typecheck')
fs.mkdirSync(out);fs.writeFileSync(out+'/package.json','{"type":"module"}\n')
const emitted=ts.createProgram(roots,{...options,noEmit:false}).emit();check(emitted.diagnostics,'Emit observer');assert.equal(emitted.emitSkipped,false)
const generated=Object.fromEntries(names.map(n=>[n,sha(fs.readFileSync(out+'/public/'+n.replace(/\.ts$/,'.js')))]))
fs.writeFileSync(out+'/identity.json',JSON.stringify({instrument,compiler:ts.version,typechecked:true,tsconfigSha256:sha(fs.readFileSync(root+'/tsconfig.json')),generated,builderSha256:sha(fs.readFileSync(__filename))},null,2)+'\n')
console.log('Typechecked and emitted '+names.length+' copied observer modules')
